#!/usr/bin/env python3
"""Evaluate a MIRSAD JSON scan against an operator-curated, version-pinned manifest.

Does not contact Juice Shop or perform any security testing. Input files must
be generated by the operator; no challenge catalog is invented by this tool.

Usage (run from backend/):
    python scripts/score_juice_shop_ground_truth.py scan.json manifest.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.ground_truth import evaluate_ground_truth
from app.schemas.platform import UnifiedScanResult


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("scan", type=Path, help="MIRSAD technical JSON export")
    parser.add_argument("manifest", type=Path, help="operator-verified OWASP Juice Shop version manifest")
    parser.add_argument("--output", type=Path, help="write deterministic JSON metrics to this file")
    args = parser.parse_args()
    try:
        scan = UnifiedScanResult.model_validate(json.loads(args.scan.read_text(encoding="utf-8")))
        manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
        data = evaluate_ground_truth(scan, manifest)
    except (OSError, ValueError, TypeError) as exc:
        parser.error(f"Ground-truth evaluation refused: {exc}")
    result = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.write_text(result, encoding="utf-8")
    else:
        print(result, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
